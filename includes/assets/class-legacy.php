<?php
/**
 * Front-end compatibility for legacy (5.x) content, unconverted or converted.
 *
 * @package ZinnDigital\PBS
 */

declare( strict_types = 1 );

namespace ZinnDigital\PBS\Assets;

use ZinnDigital\PBS\Assets;
use ZinnDigital\PBS\Core\Templates;
use ZinnDigital\PBS\Licensing;
use ZinnDigital\PBS\Migrate\Media;
use ZinnDigital\PBS\Settings;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Makes legacy markup render as it did, without a single `pbs` token on the page.
 *
 * Legacy content keeps its long tail of classes (tabs, shadows, Ken Burns, tooltips, responsive
 * text, …) as stored data; converted blocks keep them in `legacyClass`. At render time:
 * - `pbs-X` class/id/for/name tokens become `<prefix>-l-X`, `pbsguid-X` becomes `<prefix>-l-guid-X`,
 *   and `data-pbs-*` attributes become `data-<prefix>-l-*` (self::rewrite_html());
 * - the content is wrapped in `<div class="<prefix>-l-main-wrapper">`, the neutral stand-in for
 *   legacy's `pbs-main-wrapper`, which most of the legacy rules hang off;
 * - the legacy front-end stylesheet (assets/legacy.css, generated by wp/bin/pbs-legacy-css.php)
 *   and the post's own `pbs_style` rules are enqueued through Assets' neutral path (an empty
 *   hidden element keeps the place legacy's inline style element held, self::style_element()).
 *
 * ⛔ PERFORMANCE: only a singular request for a post that still carries legacy markers pays for
 * any of it. The test is one regex over the post's raw content, which WordPress already holds
 * in memory, plus one meta read from the already-primed meta cache — memoised per post id for
 * the request. A page with no legacy content gets neither the stylesheet, the wrapper nor a
 * single rewritten byte.
 */
final class Legacy {

	/** Assets source key. */
	public const CSS_KEY = 'legacy.css';

	/** The legacy per-post pseudo-element stylesheet meta (kept by the converter for undo). */
	public const STYLE_META = 'pbs_style';

	/**
	 * Markers of legacy content in a post's raw content (unconverted or converted). A converted
	 * row/column/button carries `"legacy":true` and renders with legacy's structural classes;
	 * `legacyData` carries 5.x behaviour settings the compat script reads.
	 */
	private const MARKERS = '/(?<![A-Za-z0-9_])pbs(?:guid)?-|\[pbs(?:andwich)?_|"legacyClass":"[^"]|"legacy":true|"legacyData":\{"(?!class")/';

	/** Attributes whose VALUES carry class-like tokens that may start with `pbs-`. */
	private const TOKEN_ATTRS = 'class|id|for|name|list|form|headers|aria-controls|aria-labelledby|aria-describedby|aria-owns';

	/**
	 * Memoised decisions for this request.
	 *
	 * @var array<int, bool>
	 */
	private static array $cache = array();

	/**
	 * Hook the render filter and the enqueue.
	 *
	 * @return void
	 */
	public static function register(): void {
		add_filter( 'the_content', array( self::class, 'filter_content' ), 999 );
		add_action( 'wp_enqueue_scripts', array( self::class, 'enqueue_for_request' ) );
		add_filter( 'body_class', array( self::class, 'body_class' ) );
	}

	/**
	 * A legacy post that still names legacy's blank page template gets the neutral class the
	 * compat stylesheet's blank-template rules hang off.
	 *
	 * @param mixed $classes Body classes.
	 * @return mixed
	 */
	public static function body_class( $classes ) {
		if ( ! is_array( $classes ) || ! is_singular() ) {
			return $classes;
		}
		$post_id = (int) get_queried_object_id();
		if ( $post_id < 1 || ! self::post_needs_legacy( $post_id ) ) {
			return $classes;
		}
		$prefix = Settings::prefix();
		// The STORED key: Core\Templates maps the legacy key to the neutral one on read, which hid
		// it from this check and dropped legacy's blank-template body rules (min-height, spacing).
		if ( str_ends_with( Templates::stored( $post_id ), '/template-blank.php' ) ) {
			$classes[] = $prefix . '-l-template-blank';
		}
		// Legacy PREMIUM's responsive settings (class-admin-settings-responsive.php, loaded only
		// when premium code ran) put two body classes on every page unless switched off, and the
		// compat stylesheet's phone-width rules (stacking margins, responsive text sizes) hang off
		// them. ⛔ Free 5.1.0 never printed them — measured on the free fixture, and adding them
		// there moved every 390px comparison — so they follow the edition, as legacy's did.
		if ( ! Licensing::can_use_premium() ) {
			return $classes;
		}
		$options = self::legacy_options();
		if ( empty( $options['pbs_disable_responsive_text_sizes'] ) ) {
			$classes[] = $prefix . '-l-responsive-text';
		}
		if ( empty( $options['pbs_force_mobile_responsive_adjustments'] ) ) {
			$classes[] = $prefix . '-l-force-mobile-adjustments';
		}
		return $classes;
	}

	/**
	 * Legacy's `pbs_options` array, read WITHOUT instantiating any object: the raw autoloaded
	 * value (already in memory — no query) through unserialize() with allowed_classes off.
	 *
	 * @return array<string, mixed>
	 */
	public static function legacy_options(): array {
		$all = wp_load_alloptions();
		$raw = $all['pbs_options'] ?? null;
		if ( ! is_string( $raw ) || '' === $raw ) {
			return array();
		}
		if ( ! is_serialized( $raw ) ) {
			return array();
		}
		// Classes refused (no object can be built from stored data); a corrupt value is no options.
		// nosemgrep: php.lang.security.unserialize-use.unserialize-use -- 5.x stored this option serialized; allowed_classes=false makes object injection impossible.
		$value = @unserialize( trim( $raw ), array( 'allowed_classes' => false ) ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_unserialize, WordPress.PHP.NoSilencedErrors.Discouraged -- allowed_classes=false is the safe spelling.
		return is_array( $value ) ? $value : array();
	}

	/**
	 * Does this raw content (plus whether the post has legacy pseudo styles) need the compat layer?
	 *
	 * @param string $content   Raw post content.
	 * @param bool   $has_style Whether the post has a non-empty `pbs_style`.
	 * @return bool
	 */
	public static function needs_legacy( string $content, bool $has_style ): bool {
		if ( $has_style ) {
			return true;
		}
		// A post with no `pbs` substring at all cannot match; skip the regex for the common case.
		return str_contains( $content, 'pbs' ) && 1 === preg_match( self::MARKERS, $content );
	}

	/**
	 * The decision for a post, memoised for the request.
	 *
	 * @param int $post_id Post id.
	 * @return bool
	 */
	public static function post_needs_legacy( int $post_id ): bool {
		if ( isset( self::$cache[ $post_id ] ) ) {
			return self::$cache[ $post_id ];
		}
		$post = get_post( $post_id );
		if ( ! $post instanceof \WP_Post ) {
			self::$cache[ $post_id ] = false;
			return false;
		}
		self::$cache[ $post_id ] = self::needs_legacy(
			(string) $post->post_content,
			str_contains( (string) $post->post_content, 'pbs' ) && '' !== trim( (string) get_post_meta( $post_id, self::STYLE_META, true ) )
		);
		return self::$cache[ $post_id ];
	}

	/**
	 * `wp_enqueue_scripts`: the singular post being viewed, and nothing else.
	 *
	 * @return void
	 */
	public static function enqueue_for_request(): void {
		if ( is_singular() ) {
			self::maybe_enqueue_for_post( (int) get_queried_object_id() );
		}
	}

	/**
	 * Enqueue the compat stylesheet and the post's own legacy rules when the post needs them.
	 *
	 * @param int $post_id Post id.
	 * @return bool Whether anything was enqueued.
	 */
	public static function maybe_enqueue_for_post( int $post_id ): bool {
		if ( $post_id < 1 || ! self::post_needs_legacy( $post_id ) ) {
			return false;
		}
		Assets::enqueue_style( self::CSS_KEY );

		$prefix = Settings::prefix();
		$css    = self::post_style( (string) get_post_meta( $post_id, self::STYLE_META, true ), $prefix );
		if ( '' !== $css ) {
			// A handle is printed as an element id, so it is the neutral prefix and a hash.
			$handle = $prefix . '-' . substr( sha1( $css ), 0, 8 );
			wp_register_style( $handle, false, array(), PBSW_VERSION );
			wp_enqueue_style( $handle );
			wp_add_inline_style( $handle, $css );
		}
		return true;
	}

	/**
	 * `the_content`, late: rewrite legacy tokens and add the neutral main wrapper.
	 *
	 * @param mixed $content Rendered content.
	 * @return mixed
	 */
	public static function filter_content( $content ) {
		if ( ! is_string( $content ) || '' === $content ) {
			return $content;
		}
		$post_id = (int) get_the_ID();
		if ( $post_id < 1 || ! self::post_needs_legacy( $post_id ) ) {
			return $content;
		}
		$prefix = Settings::prefix();
		// A post not converted yet still names images in the legacy plugin folder (Migrate\Media).
		$content = Media::localize( $content );
		return self::style_element( $post_id, $prefix ) . '<div class="' . esc_attr( $prefix . '-l-main-wrapper' ) . '">' . self::rewrite_html( $content, $prefix ) . '</div>';
	}

	/**
	 * Legacy printed a post's own rules as `<style id="pbs-style">` at the START of the content,
	 * before its main wrapper. The rules now go to the head (a handle and wp_add_inline_style(),
	 * which WordPress.org requires), but the element's POSITION was layout: a block theme spaces
	 * a flow layout's children (`* + *`), so the wrapper after it got the block gap (measured:
	 * without it every post with pseudo styles sat 19px higher). An empty hidden element keeps
	 * that shape — invisible, like the style element it stands for.
	 *
	 * @param int    $post_id Post id.
	 * @param string $prefix  Neutral class prefix.
	 * @return string
	 */
	private static function style_element( int $post_id, string $prefix ): string {
		return '' === self::post_style( (string) get_post_meta( $post_id, self::STYLE_META, true ), $prefix ) ? '' : '<div hidden></div>';
	}

	/**
	 * Rewrite legacy tokens in HTML: token-bearing attribute values and `data-pbs-*` names.
	 *
	 * @param string $html   HTML.
	 * @param string $prefix Neutral class prefix.
	 * @return string
	 */
	public static function rewrite_html( string $html, string $prefix ): string {
		if ( ! str_contains( $html, 'pbs' ) ) {
			return $html;
		}
		return (string) preg_replace_callback(
			'/<[A-Za-z][^>]*>/',
			static function ( array $tag ) use ( $prefix ): string {
				$out = (string) preg_replace( '/(\s)data-pbs-/i', '$1data-' . $prefix . '-l-', $tag[0] );
				$out = (string) preg_replace_callback(
					'/(\s(?:' . self::TOKEN_ATTRS . ')\s*=\s*)(["\'])(.*?)\2/i',
					static fn( array $m ): string => $m[1] . $m[2] . self::rewrite_tokens( $m[3], $prefix ) . $m[2],
					$out
				);
				// In-page links to a legacy id (tab anchors): `href="#pbs-…"`.
				return (string) preg_replace_callback(
					'/(\shref\s*=\s*)(["\'])#(pbs(?:guid)?-[^"\']*)\2/i',
					static fn( array $m ): string => $m[1] . $m[2] . '#' . self::rewrite_tokens( $m[3], $prefix ) . $m[2],
					$out
				);
			},
			$html
		);
	}

	/**
	 * `pbs-X` → `<prefix>-l-X` and `pbsguid-X` → `<prefix>-l-guid-X`, token by token.
	 *
	 * @param string $value  Attribute value or CSS.
	 * @param string $prefix Neutral class prefix.
	 * @return string
	 */
	public static function rewrite_tokens( string $value, string $prefix ): string {
		$value = (string) preg_replace( '/(?<![A-Za-z0-9_-])pbsguid-/', $prefix . '-l-guid-', $value );
		return (string) preg_replace( '/(?<![A-Za-z0-9_-])pbs-/', $prefix . '-l-', $value );
	}

	/**
	 * A post's legacy pseudo-element rules, made safe to print inside a `<style>` element and
	 * pointed at the rewritten class names.
	 *
	 * @param string $css    Stored `pbs_style`.
	 * @param string $prefix Neutral class prefix.
	 * @return string
	 */
	public static function post_style( string $css, string $prefix ): string {
		// What wp_strip_all_tags() does (script/style bodies, then tags), and then no `<` at all:
		// no element can be closed or opened from here, whatever the stored value holds. A `>` on
		// its own cannot, and it is CSS's child combinator (`.pbs-col > p`), so it stays.
		$css = (string) preg_replace( '@<(script|style)[^>]*?>.*?</\1>@si', '', $css );
		$css = (string) preg_replace( '/<[^>]*>/', '', $css );
		$css = str_replace( '<', '', $css );
		// Legacy 4.4.2 wrote the literal `undefined` into some rules; legacy removed it on output.
		$css = str_replace( 'undefined', '', $css );
		// Nothing that loads or runs anything: no imports, no scripts in url(), no IE expressions.
		$css = (string) preg_replace( '/@import[^;]*;?/i', '', $css );
		$css = (string) preg_replace( '/url\(\s*[\'"]?\s*(?:javascript|vbscript|data)\s*:[^)]*\)/i', 'none', $css );
		$css = (string) preg_replace( '/expression\s*\(|behavior\s*:|-moz-binding\s*:/i', '', $css );
		$css = str_replace( 'data-pbs-', 'data-' . $prefix . '-l-', $css );
		return trim( self::rewrite_tokens( $css, $prefix ) );
	}
}
